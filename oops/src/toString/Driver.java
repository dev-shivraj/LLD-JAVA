package toString;

public class Driver {

    int driverId;
    String name;
    double rating;
    boolean isOnline;

    public Driver() {
    }

    public Driver(int driverId, String name, double rating, boolean isOnline) {
        this.driverId = driverId;
        this.name = name;
        this.rating = rating;
        this.isOnline = isOnline;
    }
}

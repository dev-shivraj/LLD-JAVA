package this_keyword;

public class Driver {

    // member variables (attributes) of the Driver class :
    int driverId;
    String name;
    double rating;
    boolean isOnline;

    public Driver() {
    }

    public Driver(int id, String n, double r, boolean online) {
        driverId = id;
        name = n;
        rating = r;
        isOnline = online;
    }
}
